package com.example.desporto24.storage;

import com.example.desporto24.configuration.MediaStorageProperties;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Component;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;
import software.amazon.awssdk.auth.credentials.AwsBasicCredentials;
import software.amazon.awssdk.auth.credentials.StaticCredentialsProvider;
import software.amazon.awssdk.regions.Region;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.S3Configuration;
import software.amazon.awssdk.services.s3.model.GetObjectRequest;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;
import software.amazon.awssdk.services.s3.model.DeleteObjectRequest;
import software.amazon.awssdk.core.sync.RequestBody;
import java.io.InputStream;
import java.io.IOException;
import java.net.URI;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/**
 * Dedicated non-public storage for future protected profile posts and stories.
 * It NEVER falls back to MediaStorage, /media/** or the public CDN.
 * A separate migration is required before the profile-private feature gate opens.
 */
@Component
@RequiredArgsConstructor
public class PrivateProfileMediaStorage {
    private static final String PREFIX = "private-profile-media/";
    private final MediaStorageProperties settings;
    private volatile S3Client client;

    public boolean isConfigured() {
        if ("local".equalsIgnoreCase(settings.getProvider())) {
            Path publicRoot = Path.of(settings.getLocalRoot()).toAbsolutePath().normalize();
            Path privateRoot = Path.of(settings.getPrivateRoot()).toAbsolutePath().normalize();
            return !privateRoot.startsWith(publicRoot) && !publicRoot.startsWith(privateRoot);
        }
        if (!"s3".equalsIgnoreCase(settings.getProvider())) return false;
        MediaStorageProperties.S3 s3 = settings.getS3();
        if (settings.getPrivateBucket() == null || settings.getPrivateBucket().isBlank()
                || settings.getPrivateBucket().equals(s3.getBucket())
                || settings.getPrivateAccessKey() == null || settings.getPrivateAccessKey().isBlank()
                || settings.getPrivateSecretKey() == null || settings.getPrivateSecretKey().isBlank()
                || settings.getPrivateAccessKey().equals(s3.getAccessKey())
                || settings.getPrivateSecretKey().equals(s3.getSecretKey())) return false;
        try {
            URI url = URI.create(s3.getEndpoint());
            return "https".equalsIgnoreCase(url.getScheme())
                    && url.getHost() != null
                    && url.getHost().toLowerCase(Locale.ROOT).endsWith(".r2.cloudflarestorage.com")
                    && (url.getRawPath() == null || url.getRawPath().isBlank() || "/".equals(url.getRawPath()))
                    && url.getRawQuery() == null && url.getRawFragment() == null;
        } catch (RuntimeException invalid) {
            return false;
        }
    }

    /** Keys are generated by the server. Reject user-supplied paths and traversal. */
    public static boolean isPrivateKey(String key) {
        return key != null && key.matches("^private-profile-media/(?:posts|stories)/[0-9]+/[A-Za-z0-9_-]+\\.(?:jpg|jpeg|png|webp|mp4|webm)$");
    }
    private void requireReady(String key) {
        if (!isPrivateKey(key)) throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Media unavailable");
        if (!isConfigured()) throw new ResponseStatusException(HttpStatus.SERVICE_UNAVAILABLE, "Private media unavailable");
    }
    public InputStream open(String key) {
        requireReady(key);
        if ("s3".equalsIgnoreCase(settings.getProvider())) {
            return client().getObject(GetObjectRequest.builder()
                    .bucket(settings.getPrivateBucket()).key(key).build());
        }
        try {
            return Files.newInputStream(privatePath(key));
        } catch (IOException unavailable) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Media unavailable");
        }
    }
    public void put(String key, byte[] data, String mime) {
        requireReady(key);
        if (data == null || data.length == 0 || data.length > 60L * 1024 * 1024) {
            throw new IllegalArgumentException("Invalid media size");
        }
        if ("s3".equalsIgnoreCase(settings.getProvider())) {
            client().putObject(PutObjectRequest.builder()
                    .bucket(settings.getPrivateBucket()).key(key).contentType(mime).build(),
                    RequestBody.fromBytes(data));
        } else {
            try {
                Path path = privatePath(key);
                Files.createDirectories(path.getParent());
                Files.write(path, data);
            } catch (IOException failure) {
                throw new IllegalStateException("Could not store private media", failure);
            }
        }
    }
    public void delete(String key) {
        requireReady(key);
        if ("s3".equalsIgnoreCase(settings.getProvider())) {
            client().deleteObject(DeleteObjectRequest.builder()
                    .bucket(settings.getPrivateBucket()).key(key).build());
        } else {
            try {
                Files.deleteIfExists(privatePath(key));
            } catch (IOException failure) {
                throw new IllegalStateException("Could not delete private media", failure);
            }
        }
    }
    private Path privatePath(String key) {
        Path root = Path.of(settings.getPrivateRoot()).toAbsolutePath().normalize();
        Path target = root.resolve(key).normalize();
        if (!target.startsWith(root)) throw new IllegalArgumentException("Invalid private media key");
        return target;
    }
    private S3Client client() {
        S3Client existing = client;
        if (existing != null) return existing;
        synchronized (this) {
            if (client == null) {
                var s3 = settings.getS3();
                client = S3Client.builder().region(Region.of(s3.getRegion()))
                    .endpointOverride(URI.create(s3.getEndpoint()))
                    .serviceConfiguration(S3Configuration.builder().pathStyleAccessEnabled(true).build())
                    .credentialsProvider(StaticCredentialsProvider.create(
                        AwsBasicCredentials.create(settings.getPrivateAccessKey(), settings.getPrivateSecretKey())))
                    .build();
            }
            return client;
        }
    }
}
