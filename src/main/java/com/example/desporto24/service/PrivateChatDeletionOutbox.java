package com.example.desporto24.service;

import com.example.desporto24.storage.PrivateChatFileStorage;
import lombok.RequiredArgsConstructor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionSynchronizationManager;

import java.util.List;

/**
 * Durable, idempotent object deletion queue for private chat attachments.
 * Enqueue in the same transaction as the message tombstone. A crashed worker
 * cannot lose a request: leases expire and the next worker retries the row.
 */
@Service
@RequiredArgsConstructor
public class PrivateChatDeletionOutbox {
    private final JdbcTemplate jdbc;
    private final PrivateChatFileStorage storage;

    public record Pending(long id, String key, int attempts) {}

    public void enqueueAll(List<String> keys) {
        if (!TransactionSynchronizationManager.isActualTransactionActive()) {
            throw new IllegalStateException("Private chat deletion requires a database transaction");
        }
        if (keys == null) return;
        for (String key : keys.stream().filter(k -> k != null && !k.isBlank()).distinct().toList()) {
            if (!key.matches("private-chat/[a-f0-9-]{36}\\.(?:jpg|png|webp|gif|pdf|webm|ogg|mp4|mp3|m4a)")) {
                throw new IllegalArgumentException("Invalid private chat object key");
            }
            jdbc.update("""
                    INSERT INTO desporto24.private_chat_deletion_outbox
                        (storage_key, attempts, next_attempt_at, created_at)
                    VALUES (?, 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
                    ON CONFLICT (storage_key) DO NOTHING
                    """, key);
        }
    }

    /** PostgreSQL claim lease allows multiple app instances to process safely. */
    public List<Pending> claimBatch() {
        return jdbc.query("""
                WITH due AS (
                    SELECT id FROM desporto24.private_chat_deletion_outbox
                    WHERE next_attempt_at <= CURRENT_TIMESTAMP
                    ORDER BY next_attempt_at, id
                    LIMIT 25 FOR UPDATE SKIP LOCKED
                )
                UPDATE desporto24.private_chat_deletion_outbox AS target
                   SET attempts = target.attempts + 1,
                       next_attempt_at = CURRENT_TIMESTAMP + INTERVAL '5 minutes'
                  FROM due WHERE target.id = due.id
                RETURNING target.id, target.storage_key, target.attempts
                """, (rs, i) -> new Pending(
                        rs.getLong("id"), rs.getString("storage_key"), rs.getInt("attempts")));
    }

    void complete(Pending row) {
        jdbc.update("""
                DELETE FROM desporto24.private_chat_deletion_outbox
                WHERE id = ? AND attempts = ?
                """, row.id(), row.attempts());
    }

    void retryLater(Pending row) {
        int delayMinutes = Math.min(1440, 1 << Math.min(10, row.attempts()));
        jdbc.update("""
                UPDATE desporto24.private_chat_deletion_outbox
                   SET next_attempt_at = CURRENT_TIMESTAMP + (? * INTERVAL '1 minute')
                 WHERE id = ? AND attempts = ?
                """, delayMinutes, row.id(), row.attempts());
    }

    @Scheduled(fixedDelay = 60_000L, initialDelay = 30_000L)
    public void processPending() {
        for (Pending row : claimBatch()) {
            try {
                // This is always an object generated by the private-chat uploader.
                // No public-bucket fallback is ever allowed.
                storage.delete(row.key());
                complete(row);
            } catch (RuntimeException failed) {
                retryLater(row);
                org.slf4j.LoggerFactory.getLogger(PrivateChatDeletionOutbox.class)
                        .warn("Private chat attachment cleanup failed; queued for retry, id={}", row.id());
            }
        }
    }
}
