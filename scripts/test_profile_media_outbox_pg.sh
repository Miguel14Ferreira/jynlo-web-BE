#!/usr/bin/env bash
# PostgreSQL 16 integration checks for durable object deletion claims.
# Uses only the isolated GitHub Actions database. No R2 access.
set -euo pipefail
psql -X -q -v ON_ERROR_STOP=1 <<'SQL'
CREATE SCHEMA IF NOT EXISTS desporto24;
CREATE TABLE desporto24.profile_media_deletion_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_key VARCHAR(800) NOT NULL UNIQUE,
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_profile_media_outbox_due
  ON desporto24.profile_media_deletion_outbox (next_attempt_at);
-- A duplicate object must produce one durable cleanup request.
INSERT INTO desporto24.profile_media_deletion_outbox (storage_key)
VALUES ('stories/19/one.jpg')
ON CONFLICT (storage_key) DO NOTHING;
INSERT INTO desporto24.profile_media_deletion_outbox (storage_key)
VALUES ('stories/19/one.jpg')
ON CONFLICT (storage_key) DO NOTHING;
INSERT INTO desporto24.profile_media_deletion_outbox (storage_key)
VALUES ('stories/19/two.jpg')
ON CONFLICT (storage_key) DO NOTHING;
DO $$
BEGIN
  IF (SELECT COUNT(*) FROM desporto24.profile_media_deletion_outbox) != 2 THEN
    RAISE EXCEPTION 'Duplicate queue keys were not idempotent';
  END IF;
END $$;
SQL

# Hold row 1 locked in a separate transaction while the claim statement
# uses SKIP LOCKED. A correctly implemented claim must select only row 2.
psql -X -q -v ON_ERROR_STOP=1 <<'SQL' >/dev/null &
BEGIN;
SELECT 1 FROM desporto24.profile_media_deletion_outbox
  WHERE storage_key = 'stories/19/one.jpg' FOR UPDATE;
SELECT pg_sleep(3);
ROLLBACK;
SQL
locker_pid=$!
trap 'wait "$locker_pid" || true' EXIT
sleep 1
psql -X -qAt -v ON_ERROR_STOP=1 <<'SQL' > /tmp/jynlo-outbox-claimed.txt
WITH due AS (
  SELECT id FROM desporto24.profile_media_deletion_outbox
  WHERE next_attempt_at <= CURRENT_TIMESTAMP
  ORDER BY next_attempt_at, id
  LIMIT 25 FOR UPDATE SKIP LOCKED
)
UPDATE desporto24.profile_media_deletion_outbox AS target
   SET attempts = target.attempts + 1,
       next_attempt_at = CURRENT_TIMESTAMP + INTERVAL '5 minutes'
  FROM due WHERE target.id = due.id
RETURNING target.storage_key || ':' || target.attempts;
SQL
if [[ "$(cat /tmp/jynlo-outbox-claimed.txt)" != 'stories/19/two.jpg:1' ]]; then
  echo "FAIL: claim did not skip locked row" >&2
  cat /tmp/jynlo-outbox-claimed.txt >&2
  exit 1
fi
wait "$locker_pid"
trap - EXIT

# Stale workers cannot delete rows after a second successful claim.
psql -X -q -v ON_ERROR_STOP=1 <<'SQL'
UPDATE desporto24.profile_media_deletion_outbox
 SET next_attempt_at = CURRENT_TIMESTAMP - INTERVAL '1 second'
 WHERE storage_key='stories/19/two.jpg';
WITH due AS (
  SELECT id FROM desporto24.profile_media_deletion_outbox
  WHERE next_attempt_at <= CURRENT_TIMESTAMP AND storage_key='stories/19/two.jpg'
  LIMIT 25 FOR UPDATE SKIP LOCKED
)
UPDATE desporto24.profile_media_deletion_outbox AS target
 SET attempts=target.attempts+1,
     next_attempt_at=CURRENT_TIMESTAMP + INTERVAL '5 minutes'
 FROM due WHERE target.id=due.id;
DELETE FROM desporto24.profile_media_deletion_outbox
 WHERE storage_key='stories/19/two.jpg' AND attempts=1;
DO $$
BEGIN
 IF (SELECT attempts FROM desporto24.profile_media_deletion_outbox
     WHERE storage_key='stories/19/two.jpg') != 2 THEN
   RAISE EXCEPTION 'Stale worker removed a newer claim';
 END IF;
END $$;
-- Failure must schedule a retry, not delete the row.
UPDATE desporto24.profile_media_deletion_outbox
 SET next_attempt_at=CURRENT_TIMESTAMP + (4 * INTERVAL '1 minute')
 WHERE storage_key='stories/19/two.jpg' AND attempts=2;
DO $$
BEGIN
 IF NOT EXISTS (
   SELECT 1 FROM desporto24.profile_media_deletion_outbox
   WHERE storage_key='stories/19/two.jpg'
     AND next_attempt_at > CURRENT_TIMESTAMP) THEN
   RAISE EXCEPTION 'Failed cleanup was not queued for a future retry';
 END IF;
END $$;
SQL
# The operational report exposes counts only, never object keys.
psql -X -qAt -v ON_ERROR_STOP=1 -f scripts/audit_profile_media_outbox.sql > /tmp/jynlo-outbox-audit.txt
python3 - <<'PY'
from pathlib import Path
report=Path('/tmp/jynlo-outbox-audit.txt').read_text().strip().split('|')
assert len(report)==7, report
queued,due,waiting,repeated,high,oldest,maximum = map(int,report)
assert queued==2 and waiting==1 and due==1, report
assert repeated==0 and high==0 and oldest==0 and maximum==2, report
print("Outbox aggregate observability: PASS")
PY

echo "PostgreSQL durable deletion queue: duplicate, concurrent claim, stale token and backoff PASS"
